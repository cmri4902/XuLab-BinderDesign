#!/bin/bash
# ---------------------------------------------------------------------------
# Xu Lab BindCraft2 - build a transfer archive for the HPC
#
# Produces one .tar.gz holding the COMPLETE source copy:
#   * every tracked upstream file, exported from the Git object store, so its
#     content is exactly the recorded revision and its line endings are LF
#   * every Xu Lab addition (lab/, README_XULAB.md, .gitattributes), whether or
#     not it has been committed yet
#   * lab/BUILD_REVISION.txt, recording the commit, tag, dirty state and the
#     SHA-256 of each lab file, so the HPC copy's provenance is reproducible
#     even when .git is not transferred
#
# Run it in Git Bash (Windows) or any POSIX shell (Linux) from the repository:
#   bash lab/scripts/make_release.sh
#   bash lab/scripts/make_release.sh /d/transfers        # choose the output dir
#
# It writes nothing inside the repository except lab/BUILD_REVISION.txt, and it
# refuses to finish if any Linux-executed script in the archive carries CRLF.
# ---------------------------------------------------------------------------
set -euo pipefail

REPOSITORY="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
OUTPUT_DIR="${1:-${XULAB_RELEASE_DIR:-$(dirname "${REPOSITORY}")/bc2_release}}"
cd "${REPOSITORY}"

command -v git > /dev/null || { echo "make_release: git is required" >&2; exit 2; }
git rev-parse --git-dir > /dev/null 2>&1 || { echo "make_release: not a git repository" >&2; exit 2; }

COMMIT="$(git rev-parse HEAD)"
SHORT="$(git rev-parse --short HEAD)"
DESCRIBE="$(git describe --tags --always 2>/dev/null || echo 'no-tag')"
COMMIT_DATE="$(git log -1 --format=%cI)"
BRANCH="$(git rev-parse --abbrev-ref HEAD 2>/dev/null || echo 'detached')"
REMOTE="$(git remote get-url origin 2>/dev/null || echo 'no-origin')"
# Tracked-file modifications only; untracked lab files are expected and listed.
if git diff --quiet HEAD -- 2>/dev/null; then DIRTY="clean"; else DIRTY="dirty"; fi
STAMP="$(date -u +%Y%m%dT%H%M%SZ)"
NAME="bindcraft2_xulab_${SHORT}_${DIRTY}_${STAMP}"

# CR detection without a regex: stripping CR changes a file only if CR is in it.
# A dollar-quoted CR pattern is not portable across shells and can degenerate
# into an empty pattern, which would then report CRLF in every file.
holds_cr() { ! tr -d '\015' < "$1" | cmp -s - "$1"; }

STAGING="$(mktemp -d)"
trap 'rm -rf "${STAGING}"' EXIT
# The archive unpacks to exactly the deployment directory name, so no rename is
# needed on the HPC: /home/ypan/BindCraft2/BindCraft2_deploy.
DEPLOY_NAME="${XULAB_DEPLOY_NAME:-BindCraft2_deploy}"
TREE="${STAGING}/${DEPLOY_NAME}"
mkdir -p "${TREE}"

echo "make_release: exporting tracked files at ${COMMIT} (${DESCRIBE}, ${DIRTY})"
# git archive reads blobs and applies .gitattributes, so the export is LF and is
# the recorded revision rather than whatever a Windows editor left on disk.
git archive --format=tar HEAD | tar -x -C "${TREE}"

echo "make_release: adding Xu Lab files from the working tree"
for item in lab README_XULAB.md .gitattributes; do
  [[ -e ${item} ]] || { echo "make_release: missing ${item}" >&2; exit 1; }
  cp -R "${item}" "${TREE}/"
done
# Development leftovers never belong in a deployment archive.
rm -rf "${TREE}/lab/scripts/__pycache__" "${TREE}/.venv" "${TREE}/lab/notebooks/.ipynb_checkpoints"
find "${TREE}" -name '__pycache__' -type d -prune -exec rm -rf {} + 2>/dev/null || true
find "${TREE}" -name '*.pyc' -delete 2>/dev/null || true

echo "make_release: normalising line endings of Linux-executed files"
# Belt and braces: git archive already emits LF, this covers the copied files.
while IFS= read -r -d '' file; do
  if holds_cr "${file}"; then
    tmp="${file}.lf"
    tr -d '\r' < "${file}" > "${tmp}" && mv "${tmp}" "${file}"
    echo "  converted to LF: ${file#${TREE}/}"
  fi
done < <(find "${TREE}" \( -name '*.sh' -o -name '*.slurm' -o -name '*.py' \
                            -o -name '*.json' -o -name '*.md' -o -name '*.toml' \
                            -o -name '*.yml' -o -name '*.yaml' -o -name '*.txt' \) -print0)

echo "make_release: writing lab/BUILD_REVISION.txt"
{
  echo "# Xu Lab BindCraft2 build revision (generated by lab/scripts/make_release.sh)"
  echo "built_utc=${STAMP}"
  echo "built_on=$(uname -s 2>/dev/null || echo unknown)"
  echo "upstream_remote=${REMOTE}"
  echo "branch=${BRANCH}"
  echo "commit=${COMMIT}"
  echo "describe=${DESCRIBE}"
  echo "commit_date=${COMMIT_DATE}"
  echo "tracked_tree_state=${DIRTY}"
  echo "tracked_file_count=$(git ls-files | wc -l | tr -d ' ')"
  echo "pyproject_version=$(grep -m1 '^version' pyproject.toml | cut -d'"' -f2)"
  echo
  echo "# SHA-256 of each Xu Lab file in this archive"
  # BUILD_REVISION.txt is excluded: hashing the file being written would record a
  # value of its own partial content.
  (cd "${TREE}" && find lab README_XULAB.md .gitattributes -type f \
      ! -name 'BUILD_REVISION.txt' | LC_ALL=C sort | xargs sha256sum)
  echo
  echo "# Untracked files in the source working tree at build time"
  git status --porcelain --untracked-files=all | grep '^??' || echo "(none)"
} > "${TREE}/lab/BUILD_REVISION.txt"
cp "${TREE}/lab/BUILD_REVISION.txt" "${REPOSITORY}/lab/BUILD_REVISION.txt"

echo "make_release: verifying the archive content"
problems=0
while IFS= read -r -d '' file; do
  if holds_cr "${file}"; then
    echo "  FAIL CRLF survived in ${file#${TREE}/}" >&2
    problems=$((problems + 1))
  fi
done < <(find "${TREE}" \( -name '*.sh' -o -name '*.slurm' \) -print0)
for required in bindcraft/__init__.py bindcraft.py bindcraft.ipynb LICENSE pyproject.toml \
                examples/pdl1.json settings/target/structures/hPDL1.pdb \
                lab/slurm/run_bindcraft_h200.slurm lab/configs/pdl1_smoke.json \
                lab/scripts/validate_outputs.py lab/scripts/hpc_preflight.sh \
                README_XULAB.md; do
  [[ -f ${TREE}/${required} ]] || { echo "  FAIL missing ${required}" >&2; problems=$((problems + 1)); }
done
weights=$(find "${TREE}/bindcraft/weights/proteinmpnn" -name '*.npz' | wc -l | tr -d ' ')
[[ ${weights} -eq 12 ]] || { echo "  FAIL expected 12 bundled MPNN checkpoints, found ${weights}" >&2; problems=$((problems + 1)); }
[[ ${problems} -eq 0 ]] || { echo "make_release: ${problems} problem(s); archive not written" >&2; exit 1; }
echo "  OK   12 bundled MPNN checkpoints, all required entry points present, no CRLF"

mkdir -p "${OUTPUT_DIR}"
ARCHIVE="${OUTPUT_DIR}/${NAME}.tar.gz"
tar -czf "${ARCHIVE}" -C "${STAGING}" "${DEPLOY_NAME}"
BUNDLE="${OUTPUT_DIR}/${NAME}.gitbundle"
git bundle create "${BUNDLE}" --all > /dev/null 2>&1 \
  && echo "make_release: git history bundle: ${BUNDLE}" \
  || echo "make_release: git bundle skipped (optional)"

cat <<SUMMARY

make_release: archive ready
  file     : ${ARCHIVE}
  size     : $(du -h "${ARCHIVE}" | cut -f1)
  revision : ${COMMIT} (${DESCRIBE}, tracked tree ${DIRTY})
  sha256   : $(sha256sum "${ARCHIVE}" | cut -d' ' -f1)

Transfer and unpack (replace the placeholders with your own values):
  scp "${ARCHIVE}" <user>@<hpc-host>:/home/ypan/BindCraft2/
  ssh <user>@<hpc-host>
  mkdir -p /home/ypan/BindCraft2 /project/yli4/ypan/bindcraft/{results,logs,cache/jax,tmp}
  cd /home/ypan/BindCraft2
  tar -xzf ${NAME}.tar.gz                          # unpacks into ./${DEPLOY_NAME}
  cat ${DEPLOY_NAME}/lab/BUILD_REVISION.txt        # provenance of this copy
  bash ${DEPLOY_NAME}/lab/scripts/hpc_preflight.sh
SUMMARY
